export const mergeCpvOptions = (
  ...lists: Array<readonly CpvOption[] | CpvOption[] | undefined>
): CpvOption[] => {
  const map = new Map<string, string>();
  for (const list of lists) {
    for (const row of list ?? []) {
      const code = row.code.trim();
      if (!code) continue;
      if (!map.has(code)) map.set(code, row.label.trim());
    }
  }
  return [...map.entries()].map(([code, label]) => ({ code, label }));
};
